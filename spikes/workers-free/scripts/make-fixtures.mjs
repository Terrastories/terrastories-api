// Generates Rails-format bcrypt fixtures ($2a$, as bcrypt-ruby emits) for the spike Worker.
// The password is a throwaway test value, not a credential.
import { writeFileSync } from 'node:fs';
import bcrypt from 'bcryptjs';

const PASSWORD = 'spike-password-not-a-secret';
const fixtures = {};
for (const cost of [10, 11, 12]) {
  // bcryptjs emits $2b$; bcrypt-ruby emits $2a$. Both compute the same hash for
  // passwords under 72 bytes, so rewrite the prefix to the Rails encoding.
  const hash = bcrypt.hashSync(PASSWORD, cost).replace(/^\$2b\$/, '$2a$');
  if (!bcrypt.compareSync(PASSWORD, hash))
    throw new Error(`fixture ${cost} does not verify`);
  fixtures[cost] = hash;
}
writeFileSync(
  new URL('../src/fixtures.js', import.meta.url),
  `// Generated by scripts/make-fixtures.mjs. Throwaway test password only.\nexport const PASSWORD = ${JSON.stringify(PASSWORD)};\nexport const BCRYPT = ${JSON.stringify(fixtures, null, 2)};\n`
);
console.log('wrote src/fixtures.js');
